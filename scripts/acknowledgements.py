#!/usr/bin/env python3
"""Builds the open source notices from scripts/licenses/components.json:

  Bottari/Acknowledgements.json   read by the app's "오픈 소스 라이선스" window
  docs/THIRD_PARTY_NOTICES.md     the same for the repository

Versions marked `resolved` come from the app's Package.resolved, so the notices
follow dependency updates. Run it after changing a dependency:

  python3 scripts/acknowledgements.py
"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
licenses = root / "scripts" / "licenses"
resolved_file = root / "Bottari.xcodeproj/project.xcworkspace/xcshareddata/swiftpm/Package.resolved"

LGPL_NOTE = {
    "ko": (
        "Bottari는 영상 재생에 libmpv와 FFmpeg 같은 LGPL 라이브러리(MPVKit의 LGPL 빌드)를 정적으로 링크합니다. "
        "Bottari의 소스 코드는 MIT 라이선스로 https://github.com/Piorosen/Bottari 에 공개되어 있어, "
        "이 라이브러리를 고치거나 다른 버전으로 바꾼 뒤 앱을 다시 빌드할 수 있습니다"
        "(Packages/BottariKit/Package.swift의 MPVKit 의존성을 바꾸고 README의 빌드 안내를 따르십시오). "
        "각 라이브러리의 소스는 아래 저장소와, 이 버전의 MPVKit 저장소에 있는 빌드 스크립트에서 받을 수 있습니다. "
        "요청하시면 이 버전을 배포한 날로부터 3년 동안 해당 소스의 사본을 드립니다: https://github.com/Piorosen/Bottari/issues"
    ),
    "en": (
        "Bottari statically links LGPL libraries such as libmpv and FFmpeg (the LGPL build of MPVKit) for video playback. "
        "Bottari's own source code is published under the MIT License at https://github.com/Piorosen/Bottari, "
        "so you can modify these libraries, or swap in other versions, and rebuild the app "
        "(change the MPVKit dependency in Packages/BottariKit/Package.swift and follow the build steps in the README). "
        "The source of each library is available from the repositories listed below and from the build scripts in the "
        "MPVKit repository at the version shown. On request, we will provide a copy of that source for three years "
        "from the release of this version: https://github.com/Piorosen/Bottari/issues"
    ),
}

GROUPS = {
    "player": ("영상 재생 (MPVKit)", "Video playback (MPVKit)"),
    "swift": ("Swift 패키지", "Swift packages"),
    "font": ("글꼴", "Fonts"),
}


def main() -> int:
    spec = json.loads((licenses / "components.json").read_text())
    pins = {pin["identity"]: pin["state"] for pin in json.loads(resolved_file.read_text())["pins"]}
    texts: dict[str, str] = {}
    components = []
    problems = []
    for item in spec["components"]:
        version = item.get("version", "")
        if "resolved" in item:
            state = pins.get(item["resolved"])
            if state is None:
                problems.append(f"{item['name']}: {item['resolved']} is not in Package.resolved")
                continue
            version = state.get("version") or state.get("revision", "")[:10]
        for name in item["files"]:
            path = licenses / name
            if not path.exists():
                problems.append(f"{item['name']}: missing {name}")
                continue
            texts[name] = path.read_text(errors="replace").strip() + "\n"
        components.append({
            "group": item["group"],
            "name": item["name"],
            "version": version,
            "license": item["license"],
            "url": item["url"],
            "files": item["files"],
            "note": item.get("note", ""),
        })
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1

    (root / "Bottari/Acknowledgements.json").write_text(
        json.dumps({"lgplNote": LGPL_NOTE, "components": components, "texts": texts}, ensure_ascii=False, separators=(",", ":"))
    )

    lines = [
        "# Third-party notices · 오픈 소스 고지",
        "",
        "Generated by `scripts/acknowledgements.py` from `scripts/licenses/`. The app shows the same in Help › 오픈 소스 라이선스.",
        "",
        "## LGPL",
        "",
        LGPL_NOTE["ko"],
        "",
        LGPL_NOTE["en"],
        "",
    ]
    for group, (ko, en) in GROUPS.items():
        lines += [f"## {en} · {ko}", "", "| Component | Version | License | Source |", "| --- | --- | --- | --- |"]
        for c in components:
            if c["group"] == group:
                lines.append(f"| {c['name']} | {c['version']} | {c['license']} | {c['url']} |")
        lines.append("")
    lines += ["## License texts", ""]
    for name, text in texts.items():
        lines += [f"### {name}", "", "```text", text.rstrip("\n"), "```", ""]
    (root / "docs/THIRD_PARTY_NOTICES.md").write_text("\n".join(lines))
    print(f"{len(components)} components, {len(texts)} texts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
